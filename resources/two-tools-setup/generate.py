#!/usr/bin/env python3
"""Write each tool's instruction file from the one rules file (R05, R34).

    python3 generate.py           # write CLAUDE.md and AGENTS.md, (re)link the skills
    python3 generate.py --check   # exit 1 if a generated file is out of date

Edit rules/RULES.md, never the generated files. Tool names and output file names live in
targets.json.
"""
import hashlib
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CFG = json.loads((ROOT / "targets.json").read_text())


def render(t, rules):
    header = (ROOT / t["header"]).read_text().rstrip()
    return (f"<!-- Generated by generate.py from {CFG['rules']}. Edit that file, not this one. -->\n\n"
            f"{header}\n\n{rules.rstrip()}\n")


def main():
    rules = (ROOT / CFG["rules"]).read_text()
    stale = []
    for t in CFG["targets"]:
        out = ROOT / t["file"]
        text = render(t, rules)
        old = out.read_text() if out.exists() else ""
        if "--check" in sys.argv:
            if old != text:
                stale.append(t["file"])
            continue
        out.write_text(text)
        link = ROOT / t["skills_link"]
        link.parent.mkdir(parents=True, exist_ok=True)
        if not link.is_symlink():
            if link.exists():
                sys.exit(f"{link} exists and is not a link; refusing to replace it")
            link.symlink_to(os.path.relpath(ROOT / "skills", link.parent))
        state = "unchanged" if old == text else "updated"
        print(f"{t['tool']:11} {t['file']:10} {state:9} sha {hashlib.sha1(text.encode()).hexdigest()[:7]}"
              f"   skills -> {os.readlink(link)}")
    if "--check" in sys.argv:
        print("out of date: " + ", ".join(stale) if stale else "all generated files up to date")
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
